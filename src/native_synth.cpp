void Synth::load_program(const u8* image) {
    if (thread_) {
        thread_->program(image);
        return;
    }
    apply_program(image);
}
void Synth::apply_program(const u8* image) {
    Dsp& d = *dsp_;
    for (unsigned i = 0; i < 128; ++i) std::memcpy(&d.COEF[i], image + 4 * i, 4);
    for (unsigned i = 0; i < 64; ++i) std::memcpy(&d.MADRS[i], image + 0x200 + 4 * i, 4);
    for (unsigned i = 0; i < 128 * 4; ++i) std::memcpy(&d.MPRO[i], image + 0x400 + 4 * i, 4);
    d.dirty = true;
}
void Synth::clear_program() {
    if (thread_) {
        thread_->command(Thread::kClear);
        return;
    }
    apply_clear();
}
void Synth::apply_clear() {
    Dsp& d = *dsp_;
    std::memset(d.COEF, 0, sizeof d.COEF);
    std::memset(d.MADRS, 0, sizeof d.MADRS);
    std::memset(d.MPRO, 0, sizeof d.MPRO);
    std::memset(d.TEMP, 0, sizeof d.TEMP);
    std::memset(d.EFREG, 0, sizeof d.EFREG);
    d.dirty = true;
}
void Synth::set_ring(unsigned rbl) {
    if (thread_) {
        thread_->command(Thread::kRing, static_cast<u8>(rbl));
        return;
    }
    dsp_->RBL = (8192u << (rbl & 3)) - 1;
}
void Synth::fill_ring(u16 word) {
    if (thread_) {
        thread_->command(Thread::kFill, 0, 0, word);
        return;
    }
    std::fill(dsp_->ring.begin(), dsp_->ring.end(), word);
}
void Synth::set_output(unsigned i, u8 level, u8 pan) {
    if (thread_) {
        thread_->command(Thread::kOutput, static_cast<u8>(i), level, pan);
        return;
    }
    apply_output(i, level, pan);
}
void Synth::apply_output(unsigned i, u8 level, u8 pan) {
    if (i < out_level_.size()) {
        out_level_[i] = level & 15;
        out_pan_[i] = pan & 31;
    }
}
void Synth::set_master(u8 volume, bool mono) {
    if (thread_) {
        thread_->command(Thread::kMaster, volume, mono ? 1 : 0);
        return;
    }
    master_ = volume & 15;
    mono_ = mono;
}

void Synth::render(s16& left, s16& right) {
    ++samples;
    // The external inputs (the disc's CD audio): into the effects processor and straight to the
    // output through outputs 16 and 17.
    s16 ext_l = 0, ext_r = 0;
    if (thread_) {
        // The split: here the voices only as the driver sees them, stepped when it next reads or
        // changes them (sync); the sound thread's copies make the sound.
        if (external)
            external(ext_l, ext_r);
        thread_->sample(ext_l, ext_r, left, right);
        return;
    }
    SampleType mixl = 0, mixr = 0;
    mix_voices(voices_.get(), voices_on_, mixl, mixr);
    if (external)
        external(ext_l, ext_r);
    finish(mixl, mixr, sends_, ext_l, ext_r, left, right);
}

// Every playing voice's sample into the direct mix and the effects' sends, in voice order. A voice
// changes only its own enabled state while it steps, so the set can be taken at the start.
void Synth::mix_voices(Voice* voices, std::uint64_t enabled, s32& mixl, s32& mixr) {
    std::memset(sends_, 0, sizeof sends_);
    for (std::uint64_t m = enabled; m; m &= m - 1)
        voices[lowest_bit(m)].step_mix(mixl, mixr);
}

void Synth::finish(s32 mixl, s32 mixr, const s32* sends, s16 ext_l, s16 ext_r, s16& left, s16& right) {
    Dsp& d = *dsp_;
    std::memcpy(d.MIXS, sends, sizeof d.MIXS);
    d.EXTS[0] = static_cast<u32>(static_cast<s32>(ext_l));
    d.EXTS[1] = static_cast<u32>(static_cast<s32>(ext_r));
    d.step();
    if (!d.stopped)
        for (unsigned i = 0; i < 16; i++)
            volume_pan(static_cast<s16>(d.EFREG[i]), out_level_[i], out_pan_[i], mixl, mixr);
    if (ext_l | ext_r) {
        volume_pan(ext_l, out_level_[16], out_pan_[16], mixl, mixr);
        volume_pan(ext_r, out_level_[17], out_pan_[17], mixl, mixr);
    }
    if (mono_)
        mixl = mixr = (mixl + mixr) >> 1;
    const s32 val = kVolumeLut[master_];
    mixl = static_cast<s32>(fp_mul<s64>(mixl, val, 15));
    mixr = static_cast<s32>(fp_mul<s64>(mixr, val, 15));
    if (soft_clip && *soft_clip) {
        // A smooth knee (the enhancement): unchanged below 24576, then tanh into the rest.
        auto soften = [](s32 x) {
            constexpr float kKnee = 24576.0f, kRange = 32767.0f - 24576.0f;
            const float a = static_cast<float>(x < 0 ? -x : x);
            if (a <= kKnee)
                return x;
            const float y = kKnee + kRange * std::tanh((a - kKnee) / kRange);
            return static_cast<s32>(x < 0 ? -y : y);
        };
        mixl = soften(mixl);
        mixr = soften(mixr);
    }
    left = static_cast<s16>(std::clamp(mixl, -32768, 32767));
    right = static_cast<s16>(std::clamp(mixr, -32768, 32767));
}

